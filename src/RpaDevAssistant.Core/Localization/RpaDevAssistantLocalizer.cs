    public string NormalizeLocale(string? locale)
    {
        return SupportedLocale.Normalize(locale);
    }

    public string Get(string key, string? locale = null, IReadOnlyDictionary<string, string?>? values = null, string? fallback = null)
    {
        var normalized = NormalizeLocale(locale);
        var value = TryGet(normalized, key) ?? TryGet(SupportedLocale.English, key) ?? fallback ?? Humanize(key);
        return ApplyValues(value, values);
    }

    private static string? TryGet(string locale, string key)
    {
        var source = locale == SupportedLocale.Turkish ? Turkish : English;
        return source.TryGetValue(key, out var value) ? value : null;
    }

    private static string ApplyValues(string value, IReadOnlyDictionary<string, string?>? values)
    {
        if (values is null || values.Count == 0)
        {
            return value;
        }

        foreach (var pair in values)
        {
            value = value.Replace("{" + pair.Key + "}", pair.Value ?? string.Empty, StringComparison.Ordinal);
        }

        return value;
    }

    private static string Humanize(string key)
    {
        var tail = key.Split('.', StringSplitOptions.RemoveEmptyEntries).LastOrDefault() ?? "Message";
        return Regex.Replace(tail, "([a-z])([A-Z])", "$1 $2");
    }
